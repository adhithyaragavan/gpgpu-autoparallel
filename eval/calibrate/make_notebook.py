#!/usr/bin/env python3
"""Write eval/colab/calibrate.ipynb from calibrate.c and calibrate.py.

    python3 eval/calibrate/make_notebook.py

The repository is private, so the notebook can't clone it: it carries both
files itself. Run this again after changing either.
"""
import base64
import gzip
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "colab", "calibrate.ipynb")


def cell(kind, text, hidden=False):
    meta = {"cellView": "form", "jupyter": {"source_hidden": True}} if hidden else {}
    c = {"cell_type": kind, "metadata": meta, "source": text.splitlines(keepends=True)}
    if kind == "code":
        c.update(execution_count=None, outputs=[])
    return c


def packed(obj):
    b = base64.b64encode(gzip.compress(json.dumps(obj).encode(), mtime=0)).decode()
    return "\n".join(b[i:i + 76] for i in range(0, len(b), 76))


def main():
    src = {n: open(os.path.join(HERE, n)).read() for n in ("calibrate.c", "calibrate.py")}
    setup = ("# Where to work: Colab's /content or Kaggle's /kaggle/working; the machine\n"
             "# file is named after the platform (colab-t4 / kaggle-t4).\n"
             "import base64, gzip, json, os\n"
             "KAGGLE = os.path.isdir('/kaggle/working')\n"
             "ROOT = '/kaggle/working' if KAGGLE else '/content'\n"
             "os.makedirs(ROOT, exist_ok=True)\n"
             "os.environ['P05_ROOT'] = ROOT  # the %%bash cells cd here\n"
             "os.environ['P05_PLATFORM'] = 'kaggle' if KAGGLE else 'colab'\n"
             # gzip + base64 in short lines: a long line freezes the editor
             "FILES = json.loads(gzip.decompress(base64.b64decode(\"\"\"\n" + packed(src) +
             "\n\"\"\")).decode())\n"
             "for name, text in FILES.items():\n"
             "    open(os.path.join(ROOT, name), 'w').write(text)\n"
             "print('working in', ROOT)\n")
    cells = [
        cell("markdown", """# P05: calibrate the cost model on a Colab or Kaggle GPU (Phase 2.3)

- **Colab:** Runtime → Change runtime type → **T4 GPU**, then Runtime → **Run all**.
- **Kaggle:** File → Import Notebook (this file); Session options: **Accelerator → GPU T4 x2**
  and **Internet on**; then **Run All** (or Save Version → Save & Run All).

About 10 minutes, most of it installing the NVIDIA HPC SDK.

It measures what the cost model needs (memory bandwidth, arithmetic rate, OpenMP
startup and thread-team cost on the host; kernel launch, host↔device copies, bandwidth,
arithmetic rate and device startup on the GPU) and prints a JSON machine file, named
after the platform (`colab-t4` or `kaggle-t4`). **Copy the JSON the last cell prints back
to Claude**; it becomes `machine/<name>.json`, used as `p05tool -machine=machine/<name>.json`.

Generated by `eval/calibrate/make_notebook.py` from `eval/calibrate/calibrate.{c,py}`:
edit those, not this notebook.
"""),
        cell("code", setup, hidden=True),
        cell("code", """%%bash
nvidia-smi --query-gpu=name,compute_cap,driver_version,memory.total --format=csv
nproc; grep -m1 'model name' /proc/cpuinfo; lscpu | grep -E '^(Thread|Core|Socket)'
"""),
        cell("code", """%%bash
# NVIDIA HPC SDK (nvc -mp=gpu): the compiler the GPU evaluation uses (NOTES.md, 2026-10-02).
set -e
if ls /opt/nvidia/hpc_sdk/Linux_x86_64/*/compilers/bin/nvc >/dev/null 2>&1; then echo "already installed"; exit 0; fi
curl -s https://developer.download.nvidia.com/hpc-sdk/ubuntu/DEB-GPG-KEY-NVIDIA-HPC-SDK \\
  | gpg --dearmor --yes -o /usr/share/keyrings/nvidia-hpcsdk-archive-keyring.gpg
echo 'deb [signed-by=/usr/share/keyrings/nvidia-hpcsdk-archive-keyring.gpg] https://developer.download.nvidia.com/hpc-sdk/ubuntu/amd64 /' \\
  > /etc/apt/sources.list.d/nvhpc.list
apt-get update -qq
PKG=$(apt-cache search --names-only '^nvhpc-[0-9]+-[0-9]+$' | awk '{print $1}' | sort -V | tail -1)
echo "Installing $PKG"; apt-get install -y -qq $PKG > /tmp/nvhpc.log 2>&1 || { tail -20 /tmp/nvhpc.log; exit 1; }
ls -d /opt/nvidia/hpc_sdk/Linux_x86_64/*/compilers/bin/nvc
"""),
        cell("code", """%%bash
cd "$P05_ROOT"
NAME="$P05_PLATFORM-t4"
NVC=$(ls -d /opt/nvidia/hpc_sdk/Linux_x86_64/*/compilers/bin/nvc | sort -V | tail -1)
CC=$(nvidia-smi --query-gpu=compute_cap --format=csv,noheader | head -1 | tr -d .)
python3 calibrate.py --name "$NAME" --gpu --cc "$NVC" --cflags "-O2 -mp=gpu -gpu=cc$CC" \\
  --notes "$P05_PLATFORM $(nvidia-smi --query-gpu=name --format=csv,noheader | head -1), host $(nproc) vCPU; nvc -mp=gpu" \\
  --out "$NAME.json"
echo; echo "===== copy everything below this line back to Claude ====="
cat "$NAME.json"
"""),
    ]
    nb = {"cells": cells, "metadata": {"accelerator": "GPU",
                                       "colab": {"provenance": []},
                                       "kernelspec": {"display_name": "Python 3",
                                                      "name": "python3"}},
          "nbformat": 4, "nbformat_minor": 0}
    with open(OUT, "w") as f:
        json.dump(nb, f, indent=1)
        f.write("\n")
    print("wrote", os.path.relpath(OUT))


if __name__ == "__main__":
    main()
