#!/usr/bin/env python3
"""Write eval/colab/ompar.ipynb from ompar_run.py and loops.jsonl.

    python3 eval/llm_baseline/ompar/make_notebook.py

The repository is private, so the notebook carries both files itself. Run
this again after changing either.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "colab", "ompar.ipynb")
OMPAR_COMMIT = "8eea3f8b7a1966bc5241291b484b13cb80af9e1a"
MONOCODER_REVISION = "938a064aaccf065c795aac7ba76a0f76e6044169"
WEIGHTS_FOLDER = "https://drive.google.com/drive/folders/1tnJf9YvjpDLktVi23TkW-rpjqfdZoybf"


def cell(kind, text):
    c = {"cell_type": kind, "metadata": {}, "source": text.splitlines(keepends=True)}
    if kind == "code":
        c.update(execution_count=None, outputs=[])
    return c


def main():
    run = open(os.path.join(HERE, "ompar_run.py")).read()
    loops = open(os.path.join(HERE, "loops.jsonl")).read()
    cells = [
        cell("markdown", """# P05: run OMPar on PolyBench's loops (Phase 2.5 item 4)

Runtime → Change runtime type → **T4 GPU**, then Runtime → **Run all**.

It installs OMPar at a pinned commit in its own Python 3.11 environment, downloads its
two models (about 4 GB: the classifier from the authors' Google Drive folder, the
generator from HuggingFace), and asks it about every `for` loop in the 30 kernels. The
last cell downloads **`results.jsonl`**: give that file to Claude.

OMPar's repository has no licence file, so nothing of it is copied into this project;
the notebook fetches it. Its classifier checkpoint is a pickle, which is one more reason
to run this on a throwaway Colab machine.

Generated by `eval/llm_baseline/ompar/make_notebook.py`: edit that, not this notebook.
"""),
        cell("code", """%%bash
nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv
free -g | head -2; df -h /content | tail -1
"""),
        cell("code", f"""%%bash
set -e
cd /content
[ -d OMPar ] || git clone -q https://github.com/Scientific-Computing-Lab/OMPar
git -C OMPar checkout -q {OMPAR_COMMIT}
git -C OMPar rev-parse HEAD
pip install -q uv
uv venv --python 3.11 --seed /content/venv
uv pip install -q --python /content/venv/bin/python torch==2.4.1 --index-url https://download.pytorch.org/whl/cu121
uv pip install -q --python /content/venv/bin/python \\
  transformers==4.44.1 tokenizers==0.19.1 huggingface_hub==0.24.6 safetensors==0.4.4 \\
  numpy==1.26.4 tree-sitter==0.20.4 gdown
"""),
        cell("code", f"""%%bash
set -e
cd /content
[ -f weights/model.bin ] || /content/venv/bin/gdown --folder -O weights {WEIGHTS_FOLDER}
ls -l weights; sha256sum weights/model.bin
/content/venv/bin/python - <<'PY'
from huggingface_hub import HfApi
sha = HfApi().model_info('MonoCoder/MonoCoder_OMP').sha
print('MonoCoder_OMP', sha)
assert sha == '{MONOCODER_REVISION}', 'the generator changed since this notebook was written'
PY
"""),
        cell("code", "%%writefile /content/ompar_run.py\n" + run),
        cell("code", "%%writefile /content/loops.jsonl\n" + loops),
        cell("code", """%%bash
set -e
cd /content/OMPar
PYTHONPATH=/content/OMPar /content/venv/bin/python /content/ompar_run.py \\
  --model_weights /content/weights /content/loops.jsonl /content/results.jsonl
wc -l /content/loops.jsonl /content/results.jsonl
"""),
        cell("code", """from google.colab import files
files.download('/content/results.jsonl')
"""),
    ]
    nb = {"cells": cells, "nbformat": 4, "nbformat_minor": 5,
          "metadata": {"accelerator": "GPU", "kernelspec": {"name": "python3", "display_name": "Python 3"}}}
    with open(OUT, "w") as f:
        json.dump(nb, f, indent=1)
        f.write("\n")


if __name__ == "__main__":
    main()
